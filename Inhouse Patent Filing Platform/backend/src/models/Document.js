const mongoose = require("mongoose");

// ============================================================
// DOCUMENT SCHEMA
// ============================================================
//
// Stores generated patent documents / PDF information.
//
// A Document belongs to one Patent and one User.
//
// ============================================================

const documentSchema = new mongoose.Schema(
  {
    // ========================================================
    // DOCUMENT TITLE
    // ========================================================

    title: {
      type: String,
      required: [
        true,
        "Document title is required.",
      ],
      trim: true,
      maxlength: [
        200,
        "Document title cannot exceed 200 characters.",
      ],
    },

    // ========================================================
    // DOCUMENT TYPE
    // ========================================================

    documentType: {
      type: String,

      enum: [
        "Patent Application",
        "Patent Report",
        "Patent PDF",
        "Supporting Document",
        "Other",
      ],

      default: "Patent Application",

      trim: true,
    },

    // ========================================================
    // PATENT REFERENCE
    // ========================================================

    patentId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Patent",
      required: false,
      default: null,
      index: true,
    },

    // ========================================================
    // OWNER / APPLICANT
    // ========================================================

    applicantId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
      index: true,
    },

    // ========================================================
    // FILE NAME
    // ========================================================

    fileName: {
      type: String,
      required: true,
      trim: true,
    },

    originalName: {
      type: String,
      default: "",
      trim: true,
    },

    name: {
      type: String,
      default: "",
      trim: true,
    },

    extension: {
      type: String,
      default: "",
      trim: true,
      lowercase: true,
    },

    // ========================================================
    // PHYSICAL FILE PATH
    // ========================================================

    filePath: {
      type: String,
      required: true,
      trim: true,
    },

    // ========================================================
    // BROWSER / DOWNLOAD URL
    // ========================================================

    fileUrl: {
      type: String,
      default: "",
      trim: true,
    },

    validationMessage: {
      type: String,
      default: "",
      trim: true,
    },

    // ========================================================
    // MIME TYPE
    // ========================================================

    mimeType: {
      type: String,
      default: "application/pdf",
      trim: true,
    },

    // ========================================================
    // FILE SIZE
    // ========================================================

    size: {
      type: Number,
      default: 0,
      min: [
        0,
        "Document size cannot be negative.",
      ],
    },

    // ========================================================
    // DOCUMENT STATUS
    // ========================================================

    status: {
      type: String,

      enum: [
        "Generated",
        "Available",
        "Archived",
        "Deleted",
        "Failed",
      ],

      default: "Generated",

      index: true,
    },

    // ========================================================
    // VERSION
    // ========================================================

    version: {
      type: Number,
      default: 1,
      min: 1,
    },

    // ========================================================
    // GENERATED AT
    // ========================================================

    generatedAt: {
      type: Date,
      default: Date.now,
    },

    // ========================================================
    // GENERATED BY
    // ========================================================

    generatedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      default: null,
    },

    generatedByName: {
      type: String,
      default: "",
      trim: true,
    },

    generatedByEmail: {
      type: String,
      default: "",
      trim: true,
      lowercase: true,
    },

    // ========================================================
    // DESCRIPTION
    // ========================================================

    description: {
      type: String,
      default: "",
      trim: true,
      maxlength: [
        1000,
        "Description cannot exceed 1000 characters.",
      ],
    },

    // ========================================================
    // ADMIN REVIEW
    // ========================================================

    adminReviewStatus: {
      type: String,
      enum: [
        "Pending",
        "Approved",
        "Changes Requested",
        "Rejected",
      ],
      default: "Pending",
      index: true,
    },

    adminReviewComment: {
      type: String,
      default: "",
      trim: true,
      maxlength: [2000, "Review comment cannot exceed 2000 characters."],
    },

    adminReviewedAt: {
      type: Date,
      default: null,
    },

    adminReviewerName: {
      type: String,
      default: "",
      trim: true,
    },

    adminReviewerEmail: {
      type: String,
      default: "",
      trim: true,
      lowercase: true,
    },

    // ========================================================
    // NOTES
    // ========================================================

    notes: {
      type: String,
      default: "",
      trim: true,
    },
  },

  // ==========================================================
  // TIMESTAMPS
  // ==========================================================

  {
    timestamps: true,
  }
);

// ============================================================
// INDEXES
// ============================================================

documentSchema.index({
  patentId: 1,
  createdAt: -1,
});

documentSchema.index({
  applicantId: 1,
  createdAt: -1,
});

documentSchema.index({
  status: 1,
  createdAt: -1,
});

// ============================================================
// NORMALIZE DATA BEFORE SAVE
// ============================================================

documentSchema.pre(
  "save",
  function (next) {
    if (this.title) {
      this.title =
        this.title.trim();
    }

    if (this.fileName) {
      this.fileName =
        this.fileName.trim();
    }

    if (this.filePath) {
      this.filePath =
        this.filePath.trim();
    }

    if (this.fileUrl) {
      this.fileUrl =
        this.fileUrl.trim();
    }

    if (this.documentType) {
      this.documentType =
        this.documentType.trim();
    }

    if (this.generatedByName) {
      this.generatedByName =
        this.generatedByName.trim();
    }

    if (this.generatedByEmail) {
      this.generatedByEmail =
        this.generatedByEmail
          .trim()
          .toLowerCase();
    }

    if (this.description) {
      this.description =
        this.description.trim();
    }

    if (this.notes) {
      this.notes =
        this.notes.trim();
    }

    next();
  }
);

// ============================================================
// EXPORT MODEL
// ============================================================
//
// Prevents:
//
// OverwriteModelError:
// Cannot overwrite `Document` model once compiled.
//
// ============================================================

module.exports =
  mongoose.models.Document ||
  mongoose.model(
    "Document",
    documentSchema
  );